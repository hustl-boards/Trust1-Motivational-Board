#!/usr/bin/env node
'use strict';

// Rebuild slides.js from the poster files on disk.
// The TV loads that file directly, so the board never calls the GitHub API.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const slidesDir = path.join(root, 'assets', 'slides');
const outFile = path.join(root, 'slides.js');
const imageExts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif']);

function listPosters(dir) {
  if (!fs.existsSync(dir)) {
    throw new Error('Poster folder not found: ' + path.relative(root, dir));
  }
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .filter((name) => !name.startsWith('.'))
    .filter((name) => imageExts.has(path.extname(name).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }));
}

function render(files) {
  const lines = files.map((name) => {
    const src = 'assets/slides/' + encodeURIComponent(name);
    return '  ' + JSON.stringify(src);
  });
  return [
    '// Generated by scripts/generate-slides.js from assets/slides. Do not edit by hand.',
    'window.SLIDES = [',
    lines.join(',\n'),
    '];',
    ''
  ].join('\n');
}

function main() {
  const files = listPosters(slidesDir);
  if (!files.length) {
    console.error('No poster images found in assets/slides. slides.js was left unchanged.');
    process.exit(1);
  }
  const next = render(files);
  const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (previous !== next) fs.writeFileSync(outFile, next);
  console.log((previous === next ? 'Unchanged' : 'Wrote') + ' ' + files.length + ' posters to slides.js');
}

main();
